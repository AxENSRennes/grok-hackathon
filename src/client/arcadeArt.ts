const clean = (text: string) => text.normalize('NFD').replace(/[\u0300-\u036f]/g, '').replace(/…/g, '...').replace(/[’‘]/g, "'").toUpperCase();

export function pixelText(ctx: CanvasRenderingContext2D, text: string, x: number, y: number, size: number, color: string) {
  ctx.fillStyle = color;
  for (const [i, letter] of Array.from(clean(text)).entries()) {
    if (letter === ' ') continue;
    (GLYPHS[letter] || GLYPHS['?']).split('/').forEach((row, py) => Array.from(row).forEach((bit, px) => {
      if (bit === '1') ctx.fillRect(x + (i * 6 + px) * size, y + py * size, size, size);
    }));
  }
}

export function drawArcadeQuestion(ctx: CanvasRenderingContext2D, text: string) {
  ctx.clearRect(0, 0, WORLD.width, 190);
  const normalized = clean(text);
  let lines: string[] = [], size = 2;
  for (size = 9; size >= 2; size--) {
    const limit = Math.floor(704 / (6 * size)); lines = [];
    for (const word of normalized.split(/\s+/)) {
      if (!lines.length || (lines.at(-1)!.length + word.length + 1) > limit) lines.push(word);
      else lines[lines.length - 1] += ` ${word}`;
    }
    if (lines.every(line => line.length <= limit) && (lines.length * 8 - 1) * size <= 126) break;
  }
  size = Math.max(2, size);
  const limit = Math.floor(704 / (6 * size));
  lines = lines.flatMap(line => line.match(new RegExp(`.{1,${limit}}`, 'g')) || ['']);
  const y = 30 + (132 - (lines.length * 8 - 1) * size) / 2;
  lines.forEach((line, i) => pixelText(ctx, line, Math.round(640 - (line.length * 6 - 1) * size / 2), Math.round(y + i * 8 * size), size, '#f1f5ff'));
}

